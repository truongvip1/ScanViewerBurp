const {chromium}=require("playwright");
const path=require("node:path");
const fs=require("node:fs");
let activeBrowser;
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:"C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe"});
  activeBrowser=browser;
  const page=await browser.newPage({viewport:{width:1100,height:1200}});
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto("file:///"+path.resolve(__dirname,"preview.html").replace(/\\/g,"/"));
  const frame=await page.locator("iframe").contentFrame();
  await frame.locator("#cw-rows tr").first().waitFor();
  await page.evaluate(()=>{document.querySelector("iframe").style.width="1024px";document.querySelector("iframe").style.maxWidth="none";});
  const root=frame.locator("#capture-workspace");
  const count=async n=>{const got=await frame.locator("#cw-rows tr").count(); if(got!==n) throw Error("Expected "+n+" rows, got "+got);};
  await count(8);
  if(!((await frame.locator("#cw-response").textContent()).includes('"id": 703'))) throw Error("Initial response missing");
  await frame.locator("#cw-source").selectOption("Login"); await count(2);
  await frame.locator("#cw-source").selectOption("all");
  await frame.locator('[data-select="6"]').click();
  await frame.locator('[data-detail="execution"]').click();
  if(await frame.locator("[data-chain]").count()!==3) throw Error("Execution chain missing");
  await frame.locator('[data-chain="7"]').click();
  if(!((await frame.locator("#cw-response").textContent()).includes("409 Conflict"))) throw Error("Linked response incorrect");
  await frame.locator('[data-filter="errors"]').click(); await count(3);
  await frame.locator('[data-bookmark="6"]').check();
  await frame.locator('[data-filter="bookmarked"]').click(); await count(2);
  await frame.locator('[data-filter="bookmarked"]').click();
  await frame.locator('[data-filter="errors"]').click();
  await frame.locator("#cw-search").fill("sample-B"); await count(1);
  if(!(await frame.locator("#cw-no-selection").isVisible())) throw Error("Filtered-out selection should clear");
  await frame.locator('[data-select="8"]').click();
  if(!((await frame.locator("#cw-response").textContent()).includes("Waiting"))) throw Error("Pending state missing");
  await frame.locator("#cw-search").fill("");
  await frame.locator("#cw-search").fill("not-in-this-sample"); await count(0);
  await frame.locator("#cw-clear-filters").click(); await count(8);
  await frame.locator('[data-select="6"]').click();
  await frame.locator("#cw-layout").selectOption("stacked");
  if(!((await frame.locator("#cw-messages").getAttribute("class")).includes("stacked"))) throw Error("Layout did not change");
  await frame.locator("#cw-layout").selectOption("side");
  await frame.locator("#cw-expand").click();
  if(await frame.locator("#cw-traffic").isVisible()) throw Error("Expand details did not hide table");
  await frame.locator("#cw-expand").click();
  await frame.locator("#cw-pause").click();
  if(!((await frame.locator("#cw-display-state").textContent()).includes("capture continues"))) throw Error("Pause state missing");
  await frame.locator("#cw-pause").click();
  await frame.locator('[data-select="6"]').click();
  await root.screenshot({path:path.join(__dirname,"wide.png")});
  for(const width of [900,736,320]){
    await page.setViewportSize({width:Math.max(400,width+60),height:1500});
    await page.evaluate(w=>{const f=document.querySelector("iframe");f.style.width=w+"px";f.style.maxWidth="none";},width);
    const size=await root.evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}));
    if(size.scroll>size.width+2) throw Error("Outer overflow "+JSON.stringify({width,...size}));
    await root.screenshot({path:path.join(__dirname,"width-"+width+".png")});
  }
  await page.emulateMedia({colorScheme:"dark"});
  await page.setViewportSize({width:1100,height:1200});
  await page.evaluate(()=>document.querySelector("iframe").style.width="1024px");
  await root.screenshot({path:path.join(__dirname,"dark.png")});
  fs.writeFileSync(path.join(__dirname,"checks.json"),JSON.stringify({passed:true,errors,checks:["source filter","row selection","execution navigation","combined filters","bookmarks","search","pending response","layout","expand details","pause display","1024/900/736/320 widths","dark theme"]},null,2));
  await browser.close();
  if(errors.length) throw Error(errors.join("\n"));
  console.log("Mockup interactions and responsive checks passed; screenshots saved.");
})().catch(async e=>{console.error(e);if(activeBrowser) await activeBrowser.close();process.exitCode=1;});
